#!/usr/bin/env python3
"""Regenerates src/spell-data.gen.ts (language list and stop words) from the app's Spelling.kt so both stay identical."""
import re, pathlib, json
root = pathlib.Path(__file__).resolve().parent.parent
k = (root.parent / 'app/src/main/java/com/matnotes/app/Spelling.kt').read_text()
sw = re.findall(r'"(\w+)" to set\("([^"]+)"\)', k)
langs = re.search(r'val languages: List<SpellLang> = listOf\((.*?)\)\.map', k, re.S).group(1)
pairs = re.findall(r'"([\w-]+):([\w-]+)"', langs)
out = "// Generated by scripts/gen-spell-data.py from Spelling.kt (language list and stop words). Do not edit.\n"
out += "export const LANGS: [string, string][] = " + json.dumps(pairs) + ";\n"
out += "export const STOPWORDS: Record<string, Set<string>> = {\n" + "".join(f'  {c}: new Set("{w}".split(" ")),\n' for c, w in sw) + "};\n"
(root / 'src/spell-data.gen.ts').write_text(out)
