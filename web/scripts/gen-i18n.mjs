// Generates src/i18n.gen.ts from the Android string resources so the web app uses the same texts (DE/EN).
import { readFileSync, writeFileSync } from 'node:fs';
const res = new URL('../../app/src/main/res/', import.meta.url);
const parse = (file) => {
  const out = {};
  const xml = readFileSync(new URL(file, res), 'utf8');
  for (const m of xml.matchAll(/<string name="([^"]+)"[^>]*>([\s\S]*?)<\/string>/g)) {
    out[m[1]] = m[2].replace(/\\'/g, "'").replace(/\\"/g, '"').replace(/\\n/g, '\n').replace(/\\@/g, '@')
      .replace(/%(\d)\$[sd]/g, '{$1}').replace(/%[sd]/g, '{1}').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>');
  }
  return out;
};
const en = parse('values/strings.xml');
const de = { ...en, ...parse('values-de/strings.xml') };
writeFileSync(new URL('../src/i18n.gen.ts', import.meta.url),
  `// Generated by scripts/gen-i18n.mjs from app/src/main/res/values*/strings.xml. Do not edit.\nexport const STRINGS: Record<'en' | 'de', Record<string, string>> = ${JSON.stringify({ en, de }, null, 1)};\n`);
console.log('strings:', Object.keys(en).length);
